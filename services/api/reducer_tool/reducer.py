if line_tracking:
  reduction_level += 1
  lt_graph = forge_name(reduction_level)
  subgraph = lt.merge_by_line(graph, is_entity_based, reduce_io, source, props)
  graph = gt.Graph(subgraph, prune=True)
  ut.to_prov_json(graph, lt_graph, prefix, props)
  source = lt_graph
elif chunked:
  reduction_level += 1
  uc_graph = forge_name(reduction_level)
  subgraph = lt.merge_by_chunk(graph, False, source, props)
  graph = gt.Graph(subgraph, prune=True)
  ut.to_prov_json(graph, uc_graph, prefix, props)
  source = uc_graph

  if reduce_io:
    reduction_level += 1
    uc_graph_io = forge_name(reduction_level)
    graph = ut.compress_io(graph, uc_graph, props, True, True, True)
    ut.to_prov_json(graph, uc_graph_io, prefix, props)
    source = uc_graph_io

if is_entity_based:
  subgraph = red.get_entity_subgraph(graph)
else:
  subgraph = red.get_activity_subgraph(graph)

patterns, vertex_to_patterns = red.find_patterns(subgraph)

while(len(patterns) > 0):
  print('ALL PATTERNS')
  for key in patterns:
    print(f'Pattern {key}:')
    for v in patterns[key]:
      print(f'\t{graph.vertex_properties['id'][v]}')

  reductibles, vertex_to_patterns = red.choose_patterns(patterns, vertex_to_patterns)
  print('REDUCING PATTERNS')
  for key in reductibles:
    print(f'Pattern {key}')

  filtered_patterns = { key: patterns[key] for key in reductibles }

  old_vertex_count = graph.num_vertices()
  old_edges_count = graph.num_edges()
  old_counts = ut.count_nodes_per_type(graph)

  reduced_graph = red.reduce(
    graph, filtered_patterns,
    vertex_to_patterns, reduce_io, source, props
  )
  reduction_level += 1
  source = forge_name(reduction_level)

  graph = gt.Graph(reduced_graph, prune=True)
  ut.to_prov_json(graph, source, prefix, props)
  
  print(f'Reduction {reduction_level}:')
  print(f'\tReduced {len(filtered_patterns)}/{len(patterns)}')
  new_counts = ut.count_nodes_per_type(reduced_graph)
  print(f'\tNodes: {old_vertex_count} -> {graph.num_vertices()}')
  print(f'\t\tActivities: {old_counts[ut.ACTIVITY]} -> {new_counts[ut.ACTIVITY]}')
  print(f'\t\tEntities: {old_counts[ut.ENTITY]} -> {new_counts[ut.ENTITY]}')
  print(f'\tEdges: {old_edges_count} -> {graph.num_edges()}')
  print('---------------------------------------------------------------------')

  if is_entity_based:
    subgraph = red.get_entity_subgraph(graph)
  else:
    subgraph = red.get_activity_subgraph(graph)
  patterns, vertex_to_patterns = red.find_patterns(subgraph)