parser = argparse.ArgumentParser(
  prog='reducer',
  description="""Given a provenance graph reduces it by means of node merging."""
)
parser.add_argument(
  'input_file', help='Path to the json file encoding the provenance graph'
)
parser.add_argument(
  '-o', '--output', default='./output',
  help="""Path to the folder into which all output files are put.
  By default all files are placed into ./output"""
)
parser.add_argument(
  '-e', '--entity_based', action='store_true',
  help="""Must be enabled when the input graph is entity-based, i.e. it relies
  on wasDerivedFrom relations between entities"""
)
parser.add_argument(
  '-p', '--props', default=None,
  help="""Path to a file in which each line contains a pair of strings defining,
  respectively, the key of a propery in entities, activities or agents (depending
  on what kind of vertex is reduced) and the type of value being stored in that
  property. A third integer value tells how each property should be treated when
  nodes are aggregated. If 0, the property is non recorded in the new node; if 1,
  a new property named <og_prop_name>_aggr is created with value, a list of all
  unique values of aggregated nodes.
  
  See graph_tools.VertexPropertyMap for a full list of accepted types."""
)
parser.add_argument(
  '-l', '--line_tracking', action='store_true',
  help="""When working with a document that embeds line tracking information,
  this option must be enabled to do a prereduction of the graph based on that
  information. The attributes that must be available in the document are:
  yprov4wfs:jupyter_cell_index, yprov4wfs:jupyter_cell_line,
  yprov4wfs:jupyter_cell_line_start, yprov4wfs:jupyter_cell_line_end. These
  attributes must be in the props file.
  """
)
parser.add_argument(
  '-c', '--chunked', action='store_true',
  help="""When working with a document that was generated by yProv4Dask and thus
  with a document in which node names carry a chunk index, merges together nodes
  whose name is the same except for the chunk index. This option has no effect
  if line_tracking is enabled.
  """
)
parser.add_argument(
  '-i', '--reduce_io', action='store_true',
  help="""If enabled looks for entities that serve as inputs to a single activity
  and aggregates them into a single entitiy. The same is done for output entities."""
)

args = parser.parse_args()

input_file = args.input_file
source_base_name, source_ext = os.path.splitext(os.path.basename(input_file))
output_dir = args.output
is_entity_based = args.entity_based
props = args.props
line_tracking = args.line_tracking
chunked = args.chunked
reduce_io = not is_entity_based and args.reduce_io

reduction_level = 0
def forge_name(level: int | str) -> str:
  file_name = f'{source_base_name}_{level}{source_ext}'
  return os.path.join(output_dir, file_name)

# Create the output dir an copy the input file in there
os.makedirs(output_dir, exist_ok=True)
source = forge_name(reduction_level)
shutil.copy(input_file, source)

graph: gt.Graph
with open(input_file, mode='r', encoding='utf-8') as file:
  graph, prefix, props = ut.from_prov_json(file, props)
  if ut.YPROVTOOLS not in prefix:
    prefix[ut.YPROVTOOLS] = ut.YPROVTOOLS_URL

def forge_motif_name(level: int | str) -> str:
  file_name = f'{source_base_name}_{level}.pdf'
  return os.path.join('motifs', file_name)

